/**
 * Regenerates src/content/<dir>/index.ts for every content folder, so adding a
 * page is just "drop a file in the folder". Runs automatically before
 * `npm run build` (prebuild) and can be run by hand: node scripts/gen-content-index.mjs
 */
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const DIRS = ['services', 'industries', 'combos', 'locations', 'blog', 'pages'];

// Optional allow-list for partial builds: CONTENT_INDEX_ALLOW=seo-company-jaipur,jaipur
const ALLOW = process.env.CONTENT_INDEX_ALLOW ? new Set(process.env.CONTENT_INDEX_ALLOW.split(',')) : null;

const ident = (f, i) => `p${i}_${f.replace(/\.ts$/, '').replace(/[^a-zA-Z0-9]/g, '_')}`;

for (const d of DIRS) {
    const dir = join(ROOT, 'src/content', d);
    if (!existsSync(dir)) continue;
    const files = readdirSync(dir)
        .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
        .filter((f) => !ALLOW || ALLOW.has(f.replace(/\.ts$/, '')))
        .sort();
    const lines = [
        '// Generated by scripts/gen-content-index.mjs. Do not edit by hand.',
        "import type { AnyPage } from '../types';",
        ...files.map((f, i) => `import ${ident(f, i)} from './${f.replace(/\.ts$/, '')}';`),
        '',
        `const pages: AnyPage[] = [${files.map(ident).join(', ')}];`,
        '',
        'export default pages;',
        '',
    ];
    writeFileSync(join(dir, 'index.ts'), lines.join('\n'));
    console.log(`content index: ${d} (${files.length})`);
}
